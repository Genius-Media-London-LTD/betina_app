  // The build script reads the texts from here (Node); the browser goes on.
  if (typeof module !== 'undefined' && module.exports) { module.exports = { T: T, SUPPORTED: SUPPORTED }; return; }

  var EN_TITLE = document.title;
  var originals = null;

  function remember() {
    originals = new Map();
    document.querySelectorAll('[data-i]').forEach(function (el) { originals.set(el, el.textContent); });
    document.querySelectorAll('[data-i-alt]').forEach(function (el) { originals.set(el, el.alt); });
  }

  function apply(lang, persist) {
    if (SUPPORTED.indexOf(lang) < 0) lang = 'en';
    if (!originals) remember();
    var dict = T[lang] || {};
    document.querySelectorAll('[data-i]').forEach(function (el) {
      var key = el.getAttribute('data-i');
      el.textContent = (lang !== 'en' && dict[key]) || originals.get(el);
    });
    document.querySelectorAll('[data-i-alt]').forEach(function (el) {
      el.alt = (lang !== 'en' && dict[el.getAttribute('data-i-alt')]) || originals.get(el);
    });
    // Links to feature pages exist only in some languages.
    document.querySelectorAll('[data-i-href]').forEach(function (el) {
      if (!el.hasAttribute('data-en-href')) el.setAttribute('data-en-href', el.getAttribute('href'));
      var href = lang === 'en' ? el.getAttribute('data-en-href') : dict[el.getAttribute('data-i-href')];
      el.style.display = href ? '' : 'none';
      if (href) el.setAttribute('href', href);
    });
    document.querySelectorAll('[data-comp]').forEach(function (el) {
      el.setAttribute('href', (lang === 'en' ? '' : '/' + lang) + '/' + el.getAttribute('data-comp'));
    });
    document.documentElement.lang = lang;
    document.title = (lang !== 'en' && dict.title) || EN_TITLE;
    var select = document.getElementById('language-select');
    if (select) select.value = lang;
    if (persist) { try { localStorage.setItem('betina_lang', lang); } catch (e) {} }
  }

  function browserLang() {
    var list = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || ''];
    for (var i = 0; i < list.length; i++) {
      var l = String(list[i]).toLowerCase().split('-')[0];
      if (SUPPORTED.indexOf(l) >= 0 && l !== 'en') return l;
    }
    return 'en';
  }

  function start() {
    var select = document.getElementById('language-select');
    if (select) select.addEventListener('change', function (e) {
      var lang = SUPPORTED.indexOf(e.target.value) >= 0 ? e.target.value : 'en';
      try { localStorage.setItem('betina_lang', lang); } catch (err) {}
      location.href = lang === 'en' ? '/' : '/' + lang;
    });
    // A language page is already in its language.
    var page = document.documentElement.lang;
    if (page !== 'en' && SUPPORTED.indexOf(page) >= 0) { if (select) select.value = page; return; }
    var query = new URLSearchParams(location.search).get('lang');
    var saved = null;
    try { saved = localStorage.getItem('betina_lang'); } catch (e) {}
    var initial = SUPPORTED.indexOf(query) >= 0 ? query : (SUPPORTED.indexOf(saved) >= 0 ? saved : browserLang());
    apply(initial, false);
    if (!query && !saved && initial === 'en') {
      fetch('/api/locale', { credentials: 'same-origin' })
        .then(function (r) { return r.ok ? r.json() : null; })
        .then(function (d) { var g = d && COUNTRY[String(d.country || '').toUpperCase()]; if (g) apply(g, false); })
        .catch(function () {});
    }
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', start);
  else start();
