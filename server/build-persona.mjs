// Builds server/api/src/persona.js from BETina's shared persona
// (supabase/functions/_shared/betina-persona.ts). The server's Node has no
// TypeScript support, so the types are stripped here (needs Node >= 23.2).
import { readFileSync, writeFileSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';

const here = new URL('.', import.meta.url);
const src = readFileSync(new URL('../supabase/functions/_shared/betina-persona.ts', here), 'utf8');
writeFileSync(
  new URL('./api/src/persona.js', here),
  `// Generated by server/build-persona.mjs from supabase/functions/_shared/betina-persona.ts — do not edit.\n${stripTypeScriptTypes(src)}`,
);
console.log('persona.js built');
