// Builds the server's copies of BETina's shared modules from
// supabase/functions/_shared/*.ts (persona + app data). The server's Node has no
// TypeScript support, so the types are stripped here (needs Node >= 23.2).
import { readFileSync, writeFileSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';

const here = new URL('.', import.meta.url);
for (const [from, to] of [['betina-persona.ts', 'persona.js'], ['app-data.ts', 'app-data.js']]) {
  const src = readFileSync(new URL(`../supabase/functions/_shared/${from}`, here), 'utf8');
  writeFileSync(
    new URL(`./api/src/${to}`, here),
    `// Generated by server/build-persona.mjs from supabase/functions/_shared/${from} — do not edit.\n${stripTypeScriptTypes(src)}`,
  );
  console.log(`${to} built`);
}
